<?php
/**
 * Сборка таблицы товаров для импорта в результаты квиза Marquiz.
 *
 * Здесь только превращение каталога в файл: ни сети, ни кэша, ни вывода.
 * Точка входа — marquiz.php; отдельный файл нужен, чтобы сборку можно было
 * прогнать тестом на заранее заданном каталоге (scripts/check-feeds.php).
 *
 * ФОРМАТ. Marquiz принимает CSV или XLSX, первая строка — заголовки колонок,
 * и перед импортом колонки сопоставляются с полями вручную. Полей ровно шесть:
 *
 *   Название · Внутреннее название · Описание · Цена · Изображения · Видео
 *
 * Названия колонок здесь написаны в точности как у Marquiz: тогда при загрузке
 * ничего сопоставлять не придётся, файл ляжет как есть.
 *
 * ССЫЛОК И ЧИСЕЛ ЦЕНЫ В ОПИСАНИИ НЕТ, и это осознанно. Колонки для ссылки
 * формат не предусматривает, а дописанный в текст адрес Marquiz показывает
 * как есть — голой строкой посреди описания, по которой даже нельзя кликнуть.
 * Цену Marquiz печатает сам отдельной строкой и умеет зачеркнуть её, показав
 * скидку: число, повторённое в описании, спорит с ценой над ним. Возврат на
 * сайт — это кнопка результата, она настраивается в самом квизе.
 *
 * «Внутреннее название» — наш идентификатор машины (tg-…). Он не показывается
 * человеку, зато возвращается в вебхуке Marquiz в списке подошедших
 * результатов: по нему в заявке видно, какие именно автомобили человек получил
 * в подборке, а не только то, что он «прошёл квиз».
 */

declare(strict_types=1);

require_once __DIR__ . '/catalog-source.php';
require_once __DIR__ . '/2gis-build.php';

/**
 * Сколько товаров отдаём.
 *
 * Marquiz берёт не больше трёхсот результатов на квиз, считая уже заведённые
 * вручную. Обрезаем на своей стороне: загрузка файла с превышением проходит
 * частично, и какие именно машины не доехали — в интерфейсе не видно.
 */
const MARQUIZ_LIMIT = 300;

/** Фотографий на товар: столько же, сколько показывает карточка на сайте. */
const MARQUIZ_MAX_PICTURES = 10;

/** Состояние машины словами — первая строка описания. */
const MARQUIZ_STATUS = [
    'in_stock' => 'В наличии',
    'in_transit' => 'В пути',
    'on_order' => 'Под заказ',
];

/**
 * Описание товара в результате квиза.
 *
 * Человек только что ответил на вопросы и ждёт ответа «вот что вам подходит» —
 * значит первым делом он должен увидеть то, чем машины отличаются друг от
 * друга: наличие, пробег, мотор, коробку, страну. Общий текст про импорт
 * сюда не идёт: он одинаковый у всех и превращает подборку в десять
 * одинаковых карточек. Единственное исключение — строка про «под ключ»
 * в конце: без неё цену читают как стоимость машины в Корее.
 */
function marquizDescription(array $c): string
{
    $parts = [];

    $status = MARQUIZ_STATUS[(string) ($c['status'] ?? '')] ?? '';
    $country = COUNTRIES_FROM[(string) ($c['country'] ?? '')] ?? '';
    if ($status !== '' && $country !== '') {
        $parts[] = $status . ', из ' . $country;
    } elseif ($status !== '') {
        $parts[] = $status;
    }

    $mileageKm = (int) ($c['mileageKm'] ?? 0);
    $parts[] = $mileageKm > 0
        ? 'пробег ' . number_format($mileageKm, 0, ',', ' ') . ' км'
        : 'новый, пробег 0 км';

    $engine = [];
    if ((int) ($c['engineCc'] ?? 0) > 0) {
        $engine[] = number_format(((int) $c['engineCc']) / 1000, 1, ',', '') . ' л';
    }
    if ((int) ($c['powerHp'] ?? 0) > 0) {
        $engine[] = (int) $c['powerHp'] . ' л.с.';
    }
    if (($c['fuelType'] ?? '') !== '') {
        $engine[] = lc((string) $c['fuelType']);
    }
    if ($engine) {
        $parts[] = 'двигатель ' . implode(', ', $engine);
    }

    // Коробка и привод отдельной фразой: «АКПП, полный привод» читается, а
    // «2,2 л, 202 л.с., дизель, АКПП, полный» — уже перечисление без конца.
    $transmission = [];
    if (($c['gearbox'] ?? '') !== '') {
        $transmission[] = (string) $c['gearbox'];
    }
    if (($c['drive'] ?? '') !== '') {
        $transmission[] = lc((string) $c['drive']) . ' привод';
    }
    if ($transmission) {
        $parts[] = implode(', ', $transmission);
    }

    if (($c['bodyType'] ?? '') !== '') {
        $parts[] = 'кузов — ' . lc((string) $c['bodyType']);
    }

    // Каждая фраза с заглавной: в карточке они стоят подряд и читаются как
    // предложения, а не как одна строка, которую забыли дописать.
    $text = implode('. ', array_map('ucfirst_u', $parts)) . '.';

    /*
     * Про «под ключ» сказать надо, а число назвать нельзя.
     *
     * Без этих двух слов цену читают как стоимость машины в Корее и ждут
     * доплат за доставку и таможню. Но само число Marquiz печатает над
     * описанием сам — и умеет зачеркнуть его, показав скидку. Повтори мы
     * число здесь, и в карточке одновременно окажутся новая цена, старая
     * зачёркнутая и та же старая прописью в тексте.
     */
    $text .= ' Цена под ключ: доставка, таможня, утильсбор и ЭПТС уже в ней.';

    return $text;
}

/**
 * Строки для файла: по одной на машину, годную к показу.
 *
 * Машина без цены, без названия или без фотографии в подборке выглядит как
 * ошибка сайта, а не как предложение, — такие пропускаем, как и в остальных
 * фидах.
 */
function marquizRows(array $catalog): array
{
    $cars = array_values(array_filter($catalog, 'is_array'));

    // Сначала новые: если каталог перерастёт лимит, отвалятся самые старые
    // машины, а не случайные.
    usort($cars, fn($a, $b) => (int) ($b['addedAt'] ?? 0) <=> (int) ($a['addedAt'] ?? 0));

    $rows = [];
    foreach ($cars as $c) {
        $price = feedPrice($c);
        $images = array_values(array_filter(
            (array) ($c['images'] ?? []),
            fn($i) => is_string($i) && $i !== '',
        ));
        if ($price <= 0 || empty($c['id']) || empty($c['model']) || !$images) {
            continue;
        }

        [$vendor, $model] = splitModel((string) $c['model']);
        $video = (string) ($c['video'] ?? '');

        $rows[] = [
            'name' => gisName($vendor, $model, (int) ($c['year'] ?? 0), (string) ($c['trim'] ?? '')),
            'slug' => (string) $c['id'],
            'description' => marquizDescription($c),
            'price' => $price,
            'images' => array_map('abs_url', array_slice($images, 0, MARQUIZ_MAX_PICTURES)),
            'video' => $video !== '' ? abs_url($video) : '',
        ];

        if (count($rows) >= MARQUIZ_LIMIT) {
            break;
        }
    }

    return $rows;
}

/**
 * Готовый CSV для загрузки в Marquiz.
 *
 * Точка с запятой и BOM в начале — ради Excel: с запятой он в русской локали
 * сваливает всю строку в одну ячейку, без BOM показывает кириллицу
 * кракозябрами. Marquiz принимает и такой файл, а человек по дороге обычно
 * открывает его глазами.
 */
function feedMarquizCsv(array $catalog): string
{
    $head = ['Название', 'Внутреннее название', 'Описание', 'Цена', 'Изображения', 'Видео'];

    $fh = fopen('php://temp', 'r+');
    fputcsv($fh, $head, ';', '"', '');
    foreach (marquizRows($catalog) as $r) {
        fputcsv($fh, [
            $r['name'],
            $r['slug'],
            $r['description'],
            $r['price'],
            // Разделитель «|» — первый из двух, которые Marquiz понимает.
            // Точка с запятой здесь же служит разделителем колонок.
            implode('|', $r['images']),
            $r['video'],
        ], ';', '"', '');
    }
    rewind($fh);
    $csv = (string) stream_get_contents($fh);
    fclose($fh);

    return "\xEF\xBB\xBF" . $csv;
}
