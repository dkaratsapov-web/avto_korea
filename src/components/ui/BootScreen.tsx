/**
 * Экран загрузки — тот же самый, что стоит в разметке страницы.
 *
 * Зачем отдельный компонент. Пока едет код страницы, React показывает
 * запасной вид из Suspense. Раньше там был кружок-спиннер на классах
 * Tailwind — и он оказывался невидимым ровно тогда, когда нужен: файл со
 * стилями к тому моменту ещё не скачался, классы ничего не значат, и человек
 * видел пустой экран. На медленном мобильном интернете это несколько секунд.
 *
 * Здесь ни одного класса Tailwind: разметка опирается на стили, вшитые прямо
 * в index.html. Они приезжают вместе с самой страницей, поэтому доступны
 * всегда — и до внешнего CSS, и вместо него.
 *
 * Побочная выгода: заставка из разметки и этот экран выглядят одинаково,
 * поэтому в момент запуска приложения ничего не мигает и не подпрыгивает.
 *
 * ВАЖНО: разметка продублирована в index.html (блок с классом boot). Держать
 * её в одном месте нельзя — та версия обязана быть в HTML до всякого
 * JavaScript. При правке одной правьте и вторую.
 */
