/**
 * Памятка перед переходом в Telegram — общая для /tg и /bot.
 *
 * Обе посадочные ведут не на страницу, а в чужое приложение, и переход
 * упирается в два условия на стороне человека. Не выполнено любое — кнопка
 * выглядит сломанной: нажал, и ничего не произошло. Человек уходит, а клик
 * оплачен. Поэтому предупреждаем до нажатия, а не после.
 *
 * Условий ровно два, и оба короткие. Первая версия была на три пункта с
 * подробностями — читать её никто не станет: человек пришёл по рекламе и
 * хочет нажать кнопку, а не изучать инструкцию.
 *
 * Про доступ к Telegram написано обиходно — «то, чем обычно пользуетесь».
 * Прямо называть средство обхода на рекламной посадочной нельзя, а описывать
 * симптом («не грузятся сообщения») можно: тот, кого это касается, поймёт
 * сразу, остальных фраза не задевает.
 */
export function TelegramNotice({ target }: { target: "канал" | "бот" }) {
  const where = target === "канал" ? "канал" : "бота";

  return (
    <div className="mt-5 text-[16px] leading-[1.55] text-[#222]">
      <p>Кнопка ниже открывает наш {where} в Telegram. Проверьте два момента:</p>

      <ul className="mt-4 space-y-3">
        <li>
          <b className="font-semibold">Вы вошли в Telegram на этом устройстве.</b>{" "}
          Если нет — приложение попросит номер и код подтверждения.
        </li>
        <li>
          <b className="font-semibold">Telegram открывается и грузит сообщения.</b>{" "}
          Если лента пустая или всё висит — включите то, чем обычно пользуетесь
          для доступа, и нажмите кнопку снова.
        </li>
      </ul>
    </div>
  );
}
