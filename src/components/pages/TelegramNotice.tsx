export type TelegramTarget = "канал" | "бот";

/**
 * Надпись на кнопке перехода.
 *
 * Живёт здесь, а не в самих страницах, потому что памятка на неё ссылается
 * дословно: третий шаг называет кнопку по имени. Держи их порознь — и первая
 * же правка надписи оставит в памятке указание на кнопку, которой на странице
 * больше нет.
 */
export const CTA_LABEL: Record<TelegramTarget, string> = {
  канал: "Перейти в канал",
  бот: "Запустить бота",
};

/**
 * Памятка перед переходом в Telegram — общая для /tg и /bot.
 *
 * Обе посадочные ведут не на страницу, а в чужое приложение, и переход
 * упирается в условия на стороне человека. Не выполнено любое — кнопка
 * выглядит сломанной: нажал, и ничего не произошло. Человек уходит, а клик
 * оплачен. Поэтому предупреждаем до нажатия, а не после.
 *
 * Три шага, крупно и прописными, без пояснений под ними. Пояснения тут
 * лишние: человек пришёл по рекламе нажать кнопку, а не читать инструкцию,
 * и всё, что длиннее строки, он пролистывает.
 */
export function TelegramNotice({ target }: { target: TelegramTarget }) {
  const where = target === "канал" ? "канал" : "бота";

  const steps = [
    "Проверьте авторизацию в телеграмме на этом устройстве",
    "Включите VPN",
    `Кликайте по кнопке «${CTA_LABEL[target]}»`,
  ];

  return (
    <div className="mt-5">
      <p className="text-[16px] leading-[1.55] text-[#222]">
        Кнопка ниже открывает наш {where} в Telegram. Порядок такой:
      </p>

      <ol className="mt-5 space-y-4">
        {steps.map((text, i) => (
          <li key={text} className="flex gap-3">
            {/* Номер отдельным кружком: списочные маркеры рядом с прописными
                выглядят мельче текста и теряются. */}
            <span
              aria-hidden
              className="flex h-7 w-7 flex-none items-center justify-center rounded-full bg-[#3390ec] text-[14px] font-bold text-white"
            >
              {i + 1}
            </span>
            <span className="text-[17px] font-extrabold uppercase leading-[1.3] tracking-[0.01em] text-[#111]">
              {text}
            </span>
          </li>
        ))}
      </ol>
    </div>
  );
}
