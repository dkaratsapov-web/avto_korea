import { brandOf } from "@/lib/brand";
import type { Car } from "@/data/cars";

/*
 * Правило премиум-подборки живёт здесь, а не рядом с данными каталога.
 *
 * В src/data/cars.ts лежит демо-набор машин, и он при загрузке модуля читает
 * import.meta.env — переменную сборщика, которой вне браузера не существует.
 * Из-за этого правило нельзя было проверить тестами: файл падал ещё до
 * первой проверки. Здесь же чистая логика без единой зависимости от сборки.
 */

/**
 * Премиум-подборка: отобранные марки от 4,5 млн ₽ под ключ.
 *
 * Правило одно на весь сайт — им пользуются и вкладка каталога, и блок на
 * главной. Цена берётся тверская, та же, что показана в карточке.
 *
 * Марку определяем через общий справочник, а не сравнением начала строки.
 * Раньше здесь было выражение /^(mercedes|bmw|audi)/, и оно уже начинало
 * подводить: из канала модели приходят как «MERCEDES-BENZ E300», «Mercedes
 * E300» и «AudiQ7» — слитно, без пробела. Со справочником такие написания
 * сводятся к одной марке, а заодно ловятся опечатки вроде «Hyunday» и
 * сокращение «VW» вместо «Volkswagen» — в канале пишут именно так.
 */
export const PREMIUM_MIN_PRICE = 4_500_000;

/**
 * Марки премиум-подборки — в каноническом написании справочника (см.
 * src/lib/brand.ts). Название должно совпадать с ключом словаря буква в
 * букву, иначе марка молча выпадет из подборки.
 */
const PREMIUM_BRANDS = new Set([
  "Mercedes-Benz",
  "BMW",
  "Audi",
  "Hyundai",
  "Zeekr",
  "Lexus",
  "VW",
]);

export function isPremium(c: Car): boolean {
  return (
    PREMIUM_BRANDS.has(brandOf(c.model)) &&
    (c.priceTverRub ?? c.priceRub) >= PREMIUM_MIN_PRICE
  );
}
