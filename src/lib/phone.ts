/**
 * Маска телефона.
 *
 * Общая утилита: ею пользуются формы сайта (заявка, квиз) и форма сделки в
 * CRM. Раньше маска существовала двумя копиями — они успели разойтись
 * поведением, поэтому собраны в одну.
 *
 * Форматирование намеренно происходит на каждом вводе, а не при потере
 * фокуса: человек должен видеть, что номер принят в понятном виде, пока
 * печатает, а не узнавать об этом потом.
 */

/**
 * Приводит ввод к виду «+7 (900) 000-00-00».
 *
 * Российский номер узнаётся по первой цифре: 8 меняется на 7, набранный
 * с девятки номер получает семёрку впереди.
 *
 * Если человек начал строку с «+» и следующая цифра не 7 и не 8, номер
 * считается зарубежным и маска не применяется — иначе, скажем, казахстанский
 * или армянский номер клиента превратился бы в бессмыслицу. В CRM это важнее,
 * чем на сайте: там номер не просто передаётся менеджеру, а хранится.
 */
export function maskPhone(raw: string): string {
  const foreign = /^\s*\+\s*[0-69]/.test(raw);

  if (foreign) {
    const digits = raw.replace(/\D/g, "").slice(0, 15);
    return digits ? `+${digits}` : "";
  }

  let d = raw.replace(/\D/g, "");
  if (d[0] === "8") d = "7" + d.slice(1);
  else if (d[0] === "9") d = "7" + d;
  else if (d.length > 0 && d[0] !== "7") d = "7" + d;
  d = d.slice(0, 11);

  const rest = d.slice(1);
  if (rest.length === 0) return d ? "+7" : "";

  // Разделитель ставится только когда за ним есть цифры: иначе на шестой
  // и восьмой цифре в поле повисал бы дефис в конце строки.
  let out = "+7 (" + rest.slice(0, 3);
  if (rest.length >= 3) out += ")";
  if (rest.length > 3) out += " " + rest.slice(3, 6);
  if (rest.length > 6) out += "-" + rest.slice(6, 8);
  if (rest.length > 8) out += "-" + rest.slice(8, 10);
  return out;
}

/**
 * Обработчик для полей без состояния (форма заявки читает значения при
 * отправке, а не хранит их в React).
 */
export function maskPhoneInput(event: { currentTarget: HTMLInputElement }) {
  const el = event.currentTarget;
  el.value = maskPhone(el.value);
}

/** Похоже ли на телефон, по которому можно перезвонить. */
export function isPhoneComplete(value: string): boolean {
  return (value.match(/\d/g) ?? []).length >= 10;
}
