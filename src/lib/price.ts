import type { Car } from "@/data/cars";

/**
 * Какую цену показывает сайт.
 *
 * Решение одно на весь проект и живёт здесь. До этого выражение
 * «priceTverRub ?? priceRub» было переписано в двух десятках мест — от
 * карточки и модалки до фильтров, квиза и мини-аппа. Любая смена города
 * означала два десятка одинаковых правок, и одну из них обязательно бы
 * пропустили: в каталоге цена одна, в фильтре другая, в подборке третья.
 *
 * Сейчас показываем цену под ключ ДО МОСКВЫ.
 *
 * Запасной путь — общая цена (priceRub): у части машин из канала отдельной
 * московской цены нет, и лучше показать общую, чем пустое место.
 */
export function displayPrice(car: Pick<Car, "priceMoscowRub" | "priceRub">): number {
  return car.priceMoscowRub ?? car.priceRub;
}

/** Подпись к цене — полная и короткая. Меняются вместе с displayPrice. */
export const PRICE_LABEL = "Под ключ до Москвы";
export const PRICE_LABEL_SHORT = "до Москвы";
