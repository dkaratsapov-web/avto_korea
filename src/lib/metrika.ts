/**
 * Яндекс.Метрика: номер счётчика и отправка целей.
 *
 * Цели заводятся в интерфейсе Метрики как «JavaScript-событие», идентификатор
 * должен совпадать со значением из GOALS. Отправка заявки дополнительно
 * фиксируется посещением страницы /thanks — на случай, если JS-цель не успеет
 * уйти до перехода.
 */
export const METRIKA_ID = 111166439;

/**
 * Цели. Переписка с менеджером и подписка на канал — разные действия с разной
 * ценой, поэтому и цели разные: click_* это «написать нам» (тёплый контакт,
 * почти заявка), channel_* — «пойти читать канал». Место клика уходит
 * параметром place, чтобы одна кнопка не плодила отдельную цель.
 */
export const GOALS = {
  /** Форма заявки успешно отправлена. */
  lead: "lead_submit",
  /** Написать нам в Telegram (личный чат менеджера). */
  telegram: "click_telegram",
  /** Написать нам в MAX. */
  max: "click_max",
  /** Переход в наш канал в Telegram. */
  telegramChannel: "channel_telegram",
  /** Переход в наш канал в MAX. */
  maxChannel: "channel_max",
  /** Клик по номеру телефона. */
  phone: "click_phone",
  /**
   * Открыта карточка авто. Модалка — не отдельный адрес, поэтому обычной
   * целью на просмотр страницы её не поймать: нужно JS-событие.
   */
  carView: "car_view",
  /** За визит открыто больше пяти разных карточек авто. */
  deepView: "catalog_deep_view",
  /** Переход в бота с прокладки /bot (А/Б-тест трафика из Директа). */
  bot: "click_bot",
} as const;

type Ym = (id: number, action: string, ...rest: unknown[]) => void;

/** Отправить цель. Метрики может не быть (блокировщик, локальный запуск). */
export function reachGoal(goal: string, params?: Record<string, unknown>) {
  try {
    const ym = (window as unknown as { ym?: Ym }).ym;
    ym?.(METRIKA_ID, "reachGoal", goal, params);
  } catch {
    /* аналитика не должна ломать интерфейс */
  }
}
