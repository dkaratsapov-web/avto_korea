/**
 * Порядок отзывов на витрине.
 *
 * Правило владельца: свежие отзывы идут первыми, а старые выдачи —
 * от первой к последней, как они происходили.
 *
 * Почему нельзя просто отсортировать по дате. В хранилище у отзыва есть одна
 * метка времени — момент, когда запись попала в бота. Для новых отзывов это и
 * есть дата выдачи: их пересылают сразу. А весь прежний архив заливали пачкой
 * задним числом, и там метка говорит только о том, в каком порядке видео
 * перекидывали в бота, — к хронологии выдач она отношения не имеет.
 *
 * Поэтому лента собирается из двух частей:
 *   1) всё, что пришло начиная с ARCHIVE_UNTIL, — новые отзывы, свежий сверху;
 *   2) всё, что раньше, — тот самый архив, от первой выдачи к последней.
 *
 * Дальше это работает само: каждый новый отзыв из бота встаёт в начало ленты.
 */

/**
 * Граница архива: 10 сентября 2026 года, 00:00 по Москве.
 *
 * Всё, что загружено до этого момента, — залитый пачкой архив. Если окажется,
 * что какая-то выдача из архива всё же новее границы (или наоборот), дату
 * достаточно сдвинуть здесь — остальной код не меняется.
 */
export const ARCHIVE_UNTIL = Date.UTC(2026, 8, 9, 21);

type Dated = { ts?: number };

export function orderReviews<T extends Dated>(
  list: T[],
  archiveUntil: number = ARCHIVE_UNTIL,
): T[] {
  const fresh: { item: T; ts: number; i: number }[] = [];
  const archive: { item: T; ts: number; i: number }[] = [];

  list.forEach((item, i) => {
    const ts = Number(item.ts) || 0;
    (ts >= archiveUntil ? fresh : archive).push({ item, ts, i });
  });

  // Новые: свежий сверху. При равных метках верхним остаётся тот, кто в
  // хранилище лежит раньше, — бот кладёт новую запись в начало списка.
  fresh.sort((a, b) => b.ts - a.ts || a.i - b.i);

  /*
   * Архив: от первой выдачи к последней.
   *
   * У самых первых записей метки нет вовсе — их сохранял ещё тот бот, который
   * её не проставлял. Они старше всех, поэтому идут в начало; между собой —
   * в порядке, обратном хранилищу, ведь бот пишет новое в его начало.
   */
  archive.sort((a, b) => a.ts - b.ts || b.i - a.i);

  return [...fresh, ...archive].map((entry) => entry.item);
}
